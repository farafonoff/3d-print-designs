#!/usr/bin/env bash
# Render PNG previews of every .scad in this folder except test*.scad, and
# refresh the preview section of this folder's README.md.
#   ./previews.sh          PNGs -> previews/<name>.png, README.md updated
#   ./previews.sh --stl    also export <name>.stl next to each .scad
# Each .scad's description is its leading `//` comment block.
# Env: IMGSIZE=1200,900  OPENSCAD=/path/to/openscad
set -euo pipefail
cd "$(dirname "$0")"

imgsize="${IMGSIZE:-1200,900}"
openscad="${OPENSCAD:-}"
if [[ -z "$openscad" ]]; then
    if command -v openscad >/dev/null; then openscad=openscad
    elif [[ -x /Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD ]]; then
        openscad=/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD
    else echo "OpenSCAD not found; set OPENSCAD=/path/to/openscad" >&2; exit 1; fi
fi

export_stl=0
[[ "${1:-}" == "--stl" ]] && export_stl=1

# Leading `//` comment block of a file, without the `//` and without ====/---- rules.
description() {
    awk '/^\/\// { sub(/^\/\/ ?/, ""); if ($0 !~ /^[=-]+$/) print; next } { exit }' "$1" \
        | sed -e :a -e '/^[[:space:]]*$/{$d;N;ba' -e '}'
}

mkdir -p previews
block="$(mktemp)"
fail=0
for f in *.scad; do
    name="${f%.scad}"
    [[ "$name" == test* ]] && continue
    echo "== $name"
    "$openscad" --render --autocenter --viewall --imgsize "$imgsize" \
        -o "previews/$name.png" "$f" 2>&1 | grep -Ei 'error|warning|Status' || true
    if [[ -f "previews/$name.png" ]]; then
        {
            echo "### $f"
            echo
            echo '```text'
            description "$f"
            echo '```'
            echo
            echo "![$name](previews/$name.png)"
            echo
        } >> "$block"
    else
        echo "   no preview produced for $name" >&2; fail=1
    fi
    if [[ $export_stl -eq 1 ]]; then
        "$openscad" -o "$name.stl" "$f" >/dev/null 2>&1 \
            && echo "   wrote $name.stl" || { echo "   STL export failed for $name" >&2; fail=1; }
    fi
done

# Replace the generated section of README.md (between the markers), keep the rest.
start='<!-- previews:start (generated by previews.sh, do not edit) -->'
end='<!-- previews:end -->'
[[ -f README.md ]] || printf '# %s\n\n' "$(basename "$PWD")" > README.md
grep -qF "$start" README.md || printf '\n%s\n%s\n' "$start" "$end" >> README.md
out="$(mktemp)"
awk -v start="$start" -v end="$end" -v blockfile="$block" '
    $0 == start { print; while ((getline line < blockfile) > 0) print line; skip = 1; next }
    $0 == end   { skip = 0 }
    !skip       { print }
' README.md > "$out"
mv "$out" README.md
rm -f "$block"
exit $fail
